package common.exception;

import lombok.Getter;

/**
 * 全项目共用的错误码，取值按业务域分段：10000 通用、11000 商品与采购、15000 会员、
 * 16000 购物车、17000 订单、18000 秒杀、19000 媒体、21000 库存。
 *
 * <p>code 与 msg 是前后端接口契约的一部分，改动取值需要同步前端；状态不允许类错误一律
 * 给独立码，不复用 {@link #VALID_EXCEPTION} 的字段明细结构。
 */
@Getter
public enum BaseCodeEnum {
    /** 未预期的服务端异常。触发场景：异常没有更具体的处理分支，由 {@code GlobalExceptionHandler} 兜底。 */
    UNKNOWN_EXCEPTION(10000, "未知异常"),
    /** 参数格式校验失败。触发场景：{@code @Valid} / {@code @Validated} 校验不通过，或手写抛出 {@code ValidationException}。 */
    VALID_EXCEPTION(10001, "参数格式校验失败"),
    /** JSON 格式化异常。触发场景：请求体不是合法 JSON，反序列化失败。 */
    JSON_EXCEPTION(10002, "JSON格式化异常"),
    /** 商品上架异常。触发场景：search 侧写入 Elasticsearch 失败，上架流程中断。 */
    PRODUCT_UP_EXCEPTION(11000, "商品上架异常"),
    /**
     * 商品已上架，不能删除。触发场景：SKU 还在 Elasticsearch 里挂着，
     * 删了搜索会留下点进去打不开的商品，必须先下架。
     */
    PRODUCT_UP_SHELVED_CANNOT_DELETE(11001, "商品已上架，请先下架再删除"),
    /**
     * 商品已上架，不能修改规格。触发场景：规格参数在上架时被快照进 Elasticsearch，
     * 改完不重上架会让详情页与搜索的筛选面板分叉。
     */
    PRODUCT_UP_SHELVED_CANNOT_UPDATE(11002, "商品已上架，请先下架再修改规格"),
    /**
     * 分类下还有关联数据，不能删除。触发场景：删除会让仍然存活的对象静默丢数据；
     * 具体是哪种、各有多少条放在 msg 里，对象自身随之清理的关联行不拦。
     */
    CATEGORY_IN_USE(11003, "分类下还有关联数据，不能删除"),
    /** 品牌下还有商品，不能删除。 */
    BRAND_IN_USE(11004, "品牌下还有商品，不能删除"),
    /** 属性还被商品引用，不能删除。触发场景：两张属性值表里仍有商品引用该属性。 */
    ATTR_IN_USE(11005, "属性还被商品引用，不能删除"),
    /** 商品在仓库还有库存或未完成的采购需求，不能删除。触发场景：ware 侧仍挂着该商品的 SKU。 */
    PRODUCT_WARE_IN_USE(11006, "商品在仓库还有库存或未完成的采购需求，不能删除"),
    /**
     * 仓库服务暂时不可用，无法确认商品是否还有库存。触发场景：依赖暂时读不到而非数据有引用；
     * 与"有引用"分开给码，否则调用方会去清数据，而实际上只需要重试。
     */
    PRODUCT_WARE_UNAVAILABLE(11007, "仓库服务暂时不可用，无法确认商品是否还有库存"),
    /** 商品不存在。触发场景：按 SPU 或 SKU 查询未命中。 */
    PRODUCT_NOT_FOUND(11008, "商品不存在"),

    /** 采购单不存在。触发场景：按采购单 ID 查询未命中。 */
    PURCHASE_NOT_FOUND(11100, "采购单不存在"),
    /** 采购单当前状态不支持该操作。触发场景：单子已被领取或已终态，不能再改单、删除或重新分配。 */
    PURCHASE_STATUS_INVALID(11101, "采购单当前状态不支持该操作"),
    /** 采购需求单不存在。触发场景：按需求单 ID 查询未命中。 */
    PURCHASE_DETAIL_NOT_FOUND(11102, "采购需求单不存在"),
    /** 采购需求单当前状态不支持该操作。触发场景：需求单已并入采购单或已终态，不能再改数量、删除或合并。 */
    PURCHASE_DETAIL_STATUS_INVALID(11103, "采购需求单当前状态不支持该操作"),
    /** 仓库不存在。触发场景：按仓库 ID 查询未命中。 */
    WARE_NOT_FOUND(11104, "仓库不存在"),
    /** 仓库还有库存或关联单据，不能删除。 */
    WARE_IN_USE(11105, "仓库还有库存或关联单据，不能删除"),
    /** 采购单下没有采购需求，不能领取。 */
    PURCHASE_DETAIL_EMPTY(11107, "采购单下没有采购需求，不能领取"),
    /** 采购单只能包含同一个仓库的采购需求。触发场景：选中的需求单跨仓库，或与单上已有明细不同仓库。 */
    PURCHASE_WARE_MISMATCH(11108, "采购单只能包含同一个仓库的采购需求"),
    /** 这张采购单不是分配给当前登录用户的。触发场景：采购员领取他人名下的单。 */
    PURCHASE_NOT_ASSIGNEE(11109, "这张采购单不是分配给当前登录用户的"),
    /** 请求流量过大，请稍后再试。触发场景：Sentinel 限流拦截，或下游服务降级返回。 */
    TO_MANY_REQUEST(10003, "请求流量过大，请稍后再试"),

    /** 验证码获取频率太高，请稍后再试。触发场景：距上次发送不足发送间隔就再次请求，短信与邮箱验证码共用本码。 */
    SMS_CODE_EXCEPTION(10004,"验证码获取频率太高，请稍后再试"),
    /** 邮件发送失败，请稍后重试。触发场景：third-party 侧调用邮件服务失败。 */
    EMAIL_SEND_EXCEPTION(10007,"邮件发送失败，请稍后重试"),
    /**
     * 请求方式、路径或内容类型不被接受。触发场景：405 方法不支持、415 媒体类型不支持这类调用方式错误；
     * HTTP 状态码同样压平成 200，具体状态只进日志。
     */
    REQUEST_NOT_ACCEPTABLE(10006, "请求方式、路径或内容类型不被接受，请检查调用方式"),
    /** 存在相同的用户。触发场景：注册或验证码登录自动注册时账号已被占用。 */
    USER_EXIST_EXCEPTION(15001,"存在相同的用户"),
    /** 商品库存不足。触发场景：锁库存失败，order 侧用 {@code BaseException} 携带本码转发。 */
    NO_STOCK_EXCEPTION(21000,"商品库存不足"),
    /** 账号或密码错误。触发场景：账号密码登录、OAuth、QQ 登录查不到会员，不区分账号不存在与密码错。 */
    USERNAME_PASSWORD_EXCEPTION(15003,"账号或密码错误"),

    /**
     * 该手机号已绑定其他账号。触发场景：手机号是登录标识，库里没有唯一索引而按联系方式查人用
     * selectOne，命中两行会直接抛异常，因此绑定时必须拦住，这是防故障而不只是防重复。
     */
    MOBILE_IN_USE(15006, "该手机号已绑定其他账号"),
    /** 该邮箱已绑定其他账号。触发场景同 {@link #MOBILE_IN_USE}：邮箱也是登录标识，重复绑定会让按邮箱查人命中多行。 */
    EMAIL_IN_USE(15007, "该邮箱已绑定其他账号"),
    /** 收货地址数量已达上限。触发场景：新增收货地址时条数已达到每人上限。 */
    ADDRESS_LIMIT_EXCEEDED(15008, "收货地址数量已达上限"),

    /** 购物车中没有该商品。触发场景：拿着已不在车里的 skuId 改数量或勾选，排查方向在前端状态。 */
    CART_ITEM_NOT_FOUND(16000,"购物车中没有该商品"),
    /** 商品不存在或已下架。触发场景：加购时商品服务查不到该 SKU，排查方向在商品服务。 */
    CART_SKU_NOT_FOUND(16001,"商品不存在或已下架"),

    /**
     * 订单不存在。触发场景：订单查不到，或订单不属于当前用户；两种情况合并给同一个码，
     * 区分开等于告诉调用方"订单号存在但不属于你"，那是个用户枚举点。
     */
    ORDER_NOT_FOUND(17000,"订单不存在"),
    /** 订单令牌已失效，请刷新页面重试。触发场景：确认订单页停留过久，令牌校验不通过。 */
    ORDER_TOKEN_INVALID(17001,"订单令牌已失效，请刷新页面重试"),
    /** 商品价格已变动，请重新确认。触发场景：提交订单时价格与确认页展示的不一致。 */
    ORDER_PRICE_CHANGED(17002,"商品价格已变动，请重新确认"),
    /** 订单当前状态不支持该操作。触发场景：重复支付、取消已完成订单等状态不允许的操作。 */
    ORDER_STATUS_INVALID(17003,"订单当前状态不支持该操作"),
    /** 收货地址不存在。触发场景：下单时地址查不到或不属于当前用户。 */
    ADDRESS_NOT_FOUND(17004,"收货地址不存在"),

    /** 秒杀活动不存在或已结束。触发场景：秒杀根本不成立，与后面几个"成立但没抢到"分开给码。 */
    SECKILL_NOT_FOUND(18000,"秒杀活动不存在或已结束"),
    /**
     * 秒杀请求无效，请刷新页面后重试。触发场景：随机码对不上；随机码是上架时生成的 UUID，
     * 只在秒杀进行中下发给页面，拿过期页面的随机码来抢会落到这里，文案引导刷新而不是说"没抢到"。
     */
    SECKILL_TOKEN_INVALID(18001,"秒杀请求无效，请刷新页面后重试"),
    /** 该商品已被抢完。触发场景：库存扣减失败。 */
    SECKILL_SOLD_OUT(18002,"手慢了，该商品已被抢完"),
    /** 数量超出每人限购。触发场景：购买数量超过该场次设置的限购数。 */
    SECKILL_LIMIT_EXCEEDED(18003,"数量超出每人限购"),
    /** 用户已参与过该场秒杀。触发场景：同一用户重复抢购同一场次。 */
    SECKILL_ALREADY_BOUGHT(18004,"您已参与过本次秒杀，把机会留给别人吧"),

    /** 上传文件不能为空。触发场景：调用方没带文件或文件流为空，改参数即可解决。 */
    MEDIA_FILE_EMPTY(19000,"上传文件不能为空"),
    /** 只支持 jpg/png/gif/webp 格式的图片。触发场景：文件后缀或内容类型不在白名单内。 */
    MEDIA_FILE_TYPE_NOT_SUPPORTED(19001,"只支持 jpg/png/gif/webp 格式的图片"),
    /** 图片大小超出限制。触发场景：上传文件超过大小上限。 */
    MEDIA_FILE_TOO_LARGE(19002,"图片大小超出限制"),
    /** 文件地址不合法。触发场景：传入的文件地址不符合允许的格式。 */
    MEDIA_URL_INVALID(19003,"文件地址不合法"),
    /**
     * 文件存储失败，请稍后重试。触发场景：MinIO 侧出错；原始错误文本含 endpoint、bucket 名
     * 和 S3 错误详情，只进日志不回给调用方，避免泄露内网信息，也让前端能区分改参数与重试。
     */
    MEDIA_STORAGE_ERROR(19004,"文件存储失败，请稍后重试"),

    /** 请先登录。触发场景：网关拒绝匿名请求，返回 HTTP 200 + 本码，前端据此清 token。 */
    NOT_LOGIN_EXCEPTION(15004,"请先登录"),
    /** 登录已过期，请重新登录。触发场景：凭证过期或校验不通过，网关返回 HTTP 200 + 本码。 */
    LOGIN_EXPIRED_EXCEPTION(15005,"登录已过期，请重新登录"),

    /**
     * 登录已失效，请重新登录。触发场景：后台管理端身份缺失；401 是管理端前端识别登录失效的依据，
     * 与会员侧的 15004/15005 分开，两边"重新登录"的入口不一样。
     */
    ADMIN_NOT_LOGIN_EXCEPTION(401, "登录已失效，请重新登录"),

    /**
     * 登录状态校验失败，请稍后重试。触发场景：凭证签发方不可用；既不能当成凭证无效
     * （用户会被莫名登出），也不能放行。
     */
    AUTH_UNAVAILABLE(10005, "登录状态校验失败，请稍后重试"),
    ;


    /** 业务状态码，按业务域分段。 */
    private final int code;
    /** 提示文案，直接回给调用方。 */
    private final String msg;
    BaseCodeEnum(int code, String msg) {
        this.code = code;
        this.msg = msg;
    }

}
