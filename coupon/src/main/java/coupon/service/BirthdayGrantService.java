package coupon.service;

/**
 * 生日赠券：给当天过生日的会员发"会员赠券"。
 *
 * <p>规则来自 {@code ums_member_level.priviledge_birthday}（该等级是否有生日特权）与券自己的
 * {@code member_level}（该券限定哪个等级及以上）：**特权的判定落在券上**，所以本服务不需要按等级
 * 分组，把当天的寿星整批交给 {@link CouponService#grant(Long, java.util.List)}，由它既有的等级闸门
 * 去筛 —— 发券的校验、占额度、限领、落库只有那一份实现。
 *
 * <p>一年一张：按"该会员今年是否已收到过这张券"判重。判重不能交给每人限领（{@code per_limit}）——
 * 那是"一共能领几张"，表达不了"一年一张"。
 *
 * <p>无状态、线程安全：不持有连接与线程，依赖都由构造器注入。
 */
public interface BirthdayGrantService {

    /**
     * 给今天过生日的会员发一遍生日券。
     *
     * <p>按券逐张独立处理：某一张券发不出去（不在领取窗口、余量为 0、等级表取不到）只记日志跳过，
     * 不影响其余券，也不会让整轮任务失败。同一轮内已经发过的会员由判重排除，所以本方法可以
     * 被反复调用（任务按分钟级扫描也不会重复发）。
     *
     * @return 本次实际发出的券张数；今天没有人过生日或没有可发的券时为 0
     */
    int grantToday();
}
